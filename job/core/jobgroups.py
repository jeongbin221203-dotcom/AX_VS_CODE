def _text(p: dict) -> str:
    # 제목·키워드만 본다. 사이트 직무 이름('IT개발·데이터')을 넣으면 모든 IT 공고가 '데이터'로 잡히고,
    # 설명 앞부분에는 회사 이름('MG데이터시스템')이 섞여 엉뚱하게 맞는다.
    return " ".join(str(p.get(k) or "") for k in ("title", "keywords"))


def groups_of(p: dict) -> set[str]:
    """공고가 속한 직무들. 사이트 직무 이름이 있으면 그것으로, 없으면 세부 직무 단어로 짐작."""
